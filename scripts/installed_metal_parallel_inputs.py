def contracts(binding=None):
    require(sha(ROOT/CONTRACT)==CONTRACT_SHA,'Installed array contract changed or is not frozen.')
    installed=load(ROOT/CONTRACT);source=installed['source_contract']
    require(source['sha256']==SOURCE_SHA and sha(ROOT/source['path'])==SOURCE_SHA,'Reviewed source-array contract differs.')
    spec=load(ROOT/source['path']);checked={}
    for name,record in spec['sources'].items():
        path=ROOT/name
        if binding is not None:
            prefix=spec['package']['path']+'/'
            path=Path(binding['simulation_package']['path'])/name[len(prefix):] if name.startswith(prefix) else Path(binding['resource_root'])/name
        require(sha(checked_path(path))==record['sha256'],'Reviewed public array source/model differs: '+name)
        checked[name]=dict(path=str(path.resolve()),sha256=record['sha256'])
    if binding is not None:
        require(binding['simulation_package']['manifest_sha256']==spec['package']['manifest_sha256'],
                'Array package lies outside the fixed source contract.')
    return installed,spec,checked


def git(args,*,data=None):
    executable=shutil.which('git')
